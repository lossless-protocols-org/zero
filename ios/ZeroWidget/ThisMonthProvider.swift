import Foundation
import WidgetKit

struct ThisMonthEntry: TimelineEntry {
  let date: Date
  /// Nil: nothing to show yet, or nothing known to be true (the clock went back).
  let snapshot: WidgetSnapshot?
  /// The last entry made outside the app, while Undo is offered for it.
  var last: LastAdded? = nil
}

/// Two entries per timeline: now, and just after the next local midnight with
/// the day (and, on the 1st, the month) rolled over, so yesterday's spending
/// never shows as today's even if zero is not opened. The app reloads the
/// timeline whenever its figures change.
struct ThisMonthProvider: TimelineProvider {
  func placeholder(in context: Context) -> ThisMonthEntry {
    ThisMonthEntry(date: Date(), snapshot: .sample(from: SharedStore.snapshot()))
  }

  func getSnapshot(in context: Context, completion: @escaping (ThisMonthEntry) -> Void) {
    // The gallery shows made-up figures (in the user's currency once known), never theirs.
    if context.isPreview {
      completion(placeholder(in: context))
      return
    }
    let now = Date()
    completion(ThisMonthEntry(date: now, snapshot: SharedStore.snapshot()?.asOf(now), last: SharedStore.lastAdded(now: now)))
  }

  func getTimeline(in context: Context, completion: @escaping (Timeline<ThisMonthEntry>) -> Void) {
    let now = Date()
    let stored = SharedStore.snapshot()
    let calendar = Calendar.current
    let tomorrow = calendar.date(byAdding: .day, value: 1, to: calendar.startOfDay(for: now)) ?? now
    let midnight = tomorrow.addingTimeInterval(5)
    let last = SharedStore.lastAdded(now: now)
    var entries = [ThisMonthEntry(date: now, snapshot: stored?.asOf(now), last: last)]
    // Undo stops being offered after a while.
    if let last {
      let end = last.at.addingTimeInterval(SharedStore.undoLifetime + 1)
      if end < midnight { entries.append(ThisMonthEntry(date: end, snapshot: stored?.asOf(end))) }
    }
    entries.append(ThisMonthEntry(date: midnight, snapshot: stored?.asOf(midnight)))
    completion(Timeline(entries: entries, policy: .atEnd))
  }
}

