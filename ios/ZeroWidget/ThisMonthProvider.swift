/// The gallery's made-up month before the app has written a snapshot: plain
/// numbers (the app sends figures in the user's currency once it has run).
private enum GallerySample {
  static let preview = WidgetSnapshot.Preview(spentMonth: "12,345", spentToday: "450", budgetText: String(localized: "widget_preview_left"))
  static let budgetProgress = 0.62
}
// END generated

extension WidgetSnapshot {
  /// The gallery's made-up month: the stored snapshot's own preview figures
  /// (the user's currency and language), or plain numbers before there is one.
  static func sample(from stored: WidgetSnapshot?) -> WidgetSnapshot {
    let preview = stored?.preview ?? GallerySample.preview
    let labels = stored?.labels ?? Labels(today: String(localized: "widget_today"), addExpense: "", addIncome: "", summary: "")
    return WidgetSnapshot(
      v: version, state: "ready", locale: stored?.locale ?? "en", monthKey: "", todayKey: "",
      monthLabel: stored?.monthLabel ?? String(localized: "widget_name"),
      spentMonth: preview.spentMonth, spentToday: preview.spentToday, zero: "",
      budget: Budget(progress: GallerySample.budgetProgress, over: false, text: preview.budgetText), incomeLine: nil,
      labels: Labels(today: labels.today, addExpense: labels.addExpense, addIncome: labels.addIncome, summary: ""),
      // Category names are not figures: the gallery may show the user's own.
      quick: stored?.quick ?? [], categories: [], incomeCategoryId: nil, money: stored?.money, live: nil,
      again: sampleAgain(stored), last: nil,
      preview: preview)
  }

  /// Made-up "add again" rows for the gallery: the user's own category names
  /// (names are not figures) with the preview's made-up amount.
  private static func sampleAgain(_ stored: WidgetSnapshot?) -> [Again] {
    guard let stored else { return [] }
    return (stored.quick ?? []).prefix(2).map {
      Again(title: $0.name, categoryId: $0.id, categoryName: $0.name, amount: 0, amountText: stored.preview.spentToday)
    }
  }
}
