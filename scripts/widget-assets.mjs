#!/usr/bin/env node
/**
 * Generates everything the home-screen widgets need before the app has ever
 * run, on both platforms, from one source each (2.8; colours and preview
 * figures since audit 2026-11-08 §6.3):
 *
 * - copy: src/i18n/locales `widget.*`, `intents.*`, … → Android widget_strings.xml
 *   per locale and the iOS string catalog (ios/ZeroShared/Localizable.xcstrings).
 *   Every other label arrives in the snapshot, already translated by the app;
 * - colours and the picker's made-up figures: contracts/widget-assets.json →
 *   Android widget_colors.xml (light, dark, Android 12+ dynamic) and
 *   widget_preview_strings.xml, and the generated regions of the Swift files
 *   (ZeroColors in ZeroCards.swift, the gallery sample in ThisMonthProvider.swift).
 *
 *   node scripts/widget-assets.mjs           write them
 *   node scripts/widget-assets.mjs --check   exit 1 if any is stale (CI, __tests__/scripts/widgetAssets.test.ts)
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesDir = path.join(root, 'src/i18n/locales');
const resDir = path.join(root, 'android/app/src/main/res');
const assets = JSON.parse(fs.readFileSync(path.join(root, 'contracts/widget-assets.json'), 'utf8'));
const GENERATED = 'Generated by scripts/widget-assets.mjs from contracts/widget-assets.json. Do not edit.';

/** en-US grouping for the static fallbacks (the app formats the live preview per locale). */
const plain = value => value.toLocaleString('en-US');

/** en.json key → Android resource name. */
const KEYS = {
  name: 'widget_name',
  description: 'widget_description',
  today: 'widget_today',
  addExpense: 'widget_add_expense',
  addIncome: 'widget_add_income',
  openToStart: 'widget_open_to_start',
  addAgain: 'widget_add_again',
};

/**
 * iOS (2.8 Phase 4): one string catalog shared by the app (its App Intents)
 * and the widget extension. Key → dotted path in the locale file; i18next
 * placeholders become positional %1$@, %2$@ in the order listed.
 */
const IOS_KEYS = {
  widget_name: ['widget.name'],
  widget_description: ['widget.description'],
  widget_today: ['widget.today'],
  widget_add_expense: ['widget.addExpense'],
  widget_add_income: ['widget.addIncome'],
  widget_open_to_start: ['widget.openToStart'],
  quickadd_added: ['quickAdd.added', 'amount', 'category'],
  quickadd_added_income: ['quickAdd.addedIncome', 'amount'],
  intents_add_expense: ['intents.addExpense'],
  intents_add_expense_description: ['intents.addExpenseDescription'],
  intents_add_income: ['intents.addIncome'],
  intents_add_income_description: ['intents.addIncomeDescription'],
  intents_amount: ['intents.amount'],
  intents_amount_prompt: ['intents.amountPrompt'],
  intents_category: ['intents.category'],
  intents_category_prompt: ['intents.categoryPrompt'],
  intents_what_for: ['intents.whatFor'],
  intents_note: ['intents.note'],
  intents_not_ready: ['intents.notReady'],
  intents_bad_amount: ['intents.badAmount'],
  intents_control_name: ['intents.controlName'],
  intents_control_description: ['intents.controlDescription'],
  intents_money_in_control_description: ['intents.moneyInControlDescription'],
  intents_again: ['intents.again'],
  intents_again_description: ['intents.againDescription'],
  intents_again_empty: ['intents.againEmpty'],
  intents_repeat_last: ['intents.repeatLast'],
  intents_repeat_last_description: ['intents.repeatLastDescription'],
  intents_nothing_to_repeat: ['intents.nothingToRepeat'],
  intents_undo: ['intents.undo'],
  intents_undo_last: ['intents.undoLast'],
  intents_undo_last_description: ['intents.undoLastDescription'],
  intents_undone: ['intents.undone', 'entry'],
  intents_nothing_to_undo: ['intents.nothingToUndo'],
  intents_spending: ['intents.spending'],
  intents_spending_description: ['intents.spendingDescription'],
  intents_entry_label: ['intents.entryLabel', 'amount', 'name'],
  intents_keypad_name: ['intents.keypadName'],
  intents_keypad_description: ['intents.keypadDescription'],
  intents_type_amount: ['intents.typeAmount'],
  intents_added: ['intents.added'],
  intents_delete_key: ['intents.deleteKey'],
};
const IOS_CATALOG = path.join(root, 'ios/ZeroShared/Localizable.xcstrings');

const lookup = (strings, dotted) => dotted.split('.').reduce((node, key) => node?.[key], strings);

const iosValue = (strings, [dotted, ...placeholders]) => {
  let value = lookup(strings, dotted);
  if (typeof value !== 'string') return undefined;
  placeholders.forEach((name, i) => {
    value = value.replaceAll(`{{${name}}}`, `%${i + 1}$@`);
  });
  return value;
};

/** Catalog strings with a made-up figure filled in (the iOS gallery before the app has run). */
const IOS_PREVIEW_KEYS = {
  widget_preview_left: all => lookup(all, 'widget.left')?.replaceAll('{{amount}}', plain(assets.preview.budgetLeft)),
};

const renderCatalog = byLocale => {
  const strings = {};
  const valueOf = (key, all) => (key in IOS_KEYS ? iosValue(all, IOS_KEYS[key]) : IOS_PREVIEW_KEYS[key](all));
  for (const key of [...Object.keys(IOS_KEYS), ...Object.keys(IOS_PREVIEW_KEYS)].sort()) {
    const localizations = {};
    for (const [locale, all] of byLocale) {
      const value = valueOf(key, all);
      if (typeof value === 'string') localizations[locale] = {stringUnit: {state: 'translated', value}};
    }
    strings[key] = {extractionState: 'manual', localizations};
  }
  return `${JSON.stringify({sourceLanguage: 'en', strings, version: '1.0'}, null, 2)}\n`;
};

/**
 * Strings made from a key with a made-up figure filled in: the picker preview
 * on Android 12-14 (previewLayout), which runs before the app can say anything.
 */
const PREVIEW_KEYS = {
  widget_preview_left: strings => strings.left.replaceAll('{{amount}}', plain(assets.preview.budgetLeft)),
};

// Android string escaping: backslash, quotes, a leading @ or ?, and XML entities.
const escape = value =>
  value
    .replaceAll('\\', '\\\\')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('"', '\\"')
    .replace(/^([@?])/, '\\$1');

/** Android resource folder for a locale file name: en → values, pt-BR → values-pt-rBR. */
const folderFor = locale => {
  if (locale === 'en') return 'values';
  const [lang, region] = locale.split('-');
  return region ? `values-${lang}-r${region}` : `values-${lang}`;
};

const render = strings =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by scripts/widget-assets.mjs from src/i18n/locales. Do not edit. -->',
    '<resources>',
    ...Object.entries(KEYS).map(([key, name]) => `    <string name="${name}">${escape(strings[key])}</string>`),
    ...Object.entries(PREVIEW_KEYS).map(
      ([name, make]) => `    <string name="${name}">${escape(make(strings))}</string>`,
    ),
    '</resources>',
    '',
  ].join('\n');

const outputs = fs
  .readdirSync(localesDir)
  .filter(f => f.endsWith('.json'))
  .map(file => {
    const locale = file.replace(/\.json$/, '');
    const widget = JSON.parse(fs.readFileSync(path.join(localesDir, file), 'utf8')).widget ?? {};
    const missing = [...Object.keys(KEYS), 'left'].filter(k => typeof widget[k] !== 'string');
    if (missing.length > 0) {
      if (locale === 'en') {
        console.error(`widget-assets: en.json lacks widget.${missing.join(', widget.')}`);
        process.exit(1);
      }
      return null; // an incomplete translation falls back to English on the device
    }
    return {target: path.join(resDir, folderFor(locale), 'widget_strings.xml'), content: render(widget)};
  })
  .filter(Boolean);

const allLocales = fs
  .readdirSync(localesDir)
  .filter(f => f.endsWith('.json'))
  .map(file => [file.replace(/\.json$/, ''), JSON.parse(fs.readFileSync(path.join(localesDir, file), 'utf8'))]);
const missingIos = Object.entries(IOS_KEYS).filter(
  ([, spec]) => iosValue(Object.fromEntries(allLocales).en, spec) === undefined,
);
if (missingIos.length > 0) {
  console.error(`widget-assets: en.json lacks ${missingIos.map(([, [dotted]]) => dotted).join(', ')}`);
  process.exit(1);
}
outputs.push({target: IOS_CATALOG, content: renderCatalog(allLocales)});

// ---- colours ----------------------------------------------------------------

const androidRoles = Object.values(assets.palette).filter(role => role.android);
const colorsXml = (note, valueOf) =>
  [
    '<?xml version="1.0" encoding="utf-8"?>',
    `<!-- ${note} ${GENERATED} -->`,
    '<resources>',
    ...androidRoles.map(role => `    <color name="${role.android}">${valueOf(role)}</color>`),
    '</resources>',
    '',
  ].join('\n');
const fixedOr = (mode, role) => (role.dynamic ? `@android:color/${role.dynamic[mode]}` : role[mode]); // a role with no tonal match stays fixed
outputs.push(
  {
    target: path.join(resDir, 'values/widget_colors.xml'),
    content: colorsXml("Home-screen widget palette, Android 11 and lower: zero's light theme.", role => role.light),
  },
  {
    target: path.join(resDir, 'values-night/widget_colors.xml'),
    content: colorsXml("Home-screen widget palette, Android 11 and lower, dark: zero's dark theme.", role => role.dark),
  },
  {
    target: path.join(resDir, 'values-v31/widget_colors.xml'),
    content: colorsXml(
      "Home-screen widget palette, Android 12+: the wallpaper's tonal palettes (Material 3 roles).",
      role => fixedOr('light', role),
    ),
  },
  {
    target: path.join(resDir, 'values-night-v31/widget_colors.xml'),
    content: colorsXml("Home-screen widget palette, Android 12+, dark: the wallpaper's tonal palettes.", role =>
      fixedOr('dark', role),
    ),
  },
  {
    target: path.join(resDir, 'values/widget_preview_strings.xml'),
    content: [
      '<?xml version="1.0" encoding="utf-8"?>',
      `<!-- Made-up figures for the widget picker's preview (Android 12-14). Never user data. ${GENERATED} -->`,
      '<resources>',
      `    <string name="widget_preview_month" translatable="false">${plain(assets.preview.spentMonth)}</string>`,
      `    <string name="widget_preview_today" translatable="false">${plain(assets.preview.spentToday)}</string>`,
      '</resources>',
      '',
    ].join('\n'),
  },
);

/** Replaces the text between a file's generated-region markers; the markers themselves stay. */
const BEGIN = `// BEGIN ${GENERATED}`;
const END = '// END generated';
const region = (file, body) => {
  const target = path.join(root, file);
  const text = fs.readFileSync(target, 'utf8');
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start < 0 || end < start) {
    console.error(`widget-assets: ${file} has no generated region (${BEGIN} … ${END})`);
    process.exit(1);
  }
  return {target, content: `${text.slice(0, start + BEGIN.length)}\n${body}${text.slice(end)}`};
};
const hex = value => `0x${value.slice(1).toUpperCase()}`;
const iosRoles = Object.values(assets.palette).filter(role => role.ios);
outputs.push(
  region(
    'ios/ZeroShared/ZeroCards.swift',
    [
      "/// zero's palette, light and dark. On iOS 26+ Home Screens the system tints",
      '/// or glasses widgets itself (accented rendering); these apply in full colour.',
      'enum ZeroColors {',
      ...iosRoles.map(role => `  static let ${role.ios} = dynamic(light: ${hex(role.light)}, dark: ${hex(role.dark)})`),
      '',
    ].join('\n'),
  ),
  region(
    'ios/ZeroWidget/ThisMonthProvider.swift',
    [
      "/// The gallery's made-up month before the app has written a snapshot: plain",
      "/// numbers (the app sends figures in the user's currency once it has run).",
      'private enum GallerySample {',
      `  static let preview = WidgetSnapshot.Preview(spentMonth: "${plain(assets.preview.spentMonth)}", spentToday: "${plain(assets.preview.spentToday)}", budgetText: String(localized: "widget_preview_left"))`,
      `  static let budgetProgress = ${assets.preview.budgetProgress}`,
      '}',
      '',
    ].join('\n'),
  ),
);

if (process.argv.includes('--check')) {
  const stale = outputs.filter(o => !fs.existsSync(o.target) || fs.readFileSync(o.target, 'utf8') !== o.content);
  for (const o of stale) console.error(`widget-assets: stale ${path.relative(root, o.target)}`);
  console.log(`widget-assets: ${stale.length} stale`);
  process.exit(stale.length > 0 ? 1 : 0);
}
for (const o of outputs) {
  fs.mkdirSync(path.dirname(o.target), {recursive: true});
  fs.writeFileSync(o.target, o.content);
  console.log(`widget-assets: wrote ${path.relative(root, o.target)}`);
}
